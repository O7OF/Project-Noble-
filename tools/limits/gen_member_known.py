"""C12-L (d): list of slot-record access instructions that are already reviewed, for -trace-members.

Known = every traced access in docs/limits-players-sites.json (runs 1-4, reviewed in limits-players-audit.md),
the peer-table operands in src/host/SlotTableSites.inc (65), the four accesses inside the two caved table reset
loops, and the accesses reviewed after the 2026-11-09 three-instance trace (0x2A3870, 0x39DD4C). -trace-members logs any other engine instruction that touches a session's slot arrays as MEMBER-NEW.
Runtime-only discovery: nothing here scans the disassembly.

    python -I tools/limits/gen_member_known.py docs/limits-players-sites.json src/host/SlotTableSites.inc src/host/MemberKnown.inc
"""
import json, re, sys

sites, table, out = sys.argv[1:4]
known = {int(a['rva'], 16) for a in json.load(open(sites))['slot_accesses']}
# table sites: the access instruction is at rva + pre (pre = the leading lea of the biased form)
for rva, pre in re.findall(r'^\{ 0x([0-9A-F]+),.*, (\d+) \},', open(table).read(), re.M):
    known.add(int(rva, 16) + int(pre))
known |= {0x39C785, 0x39C789, 0x39C80F, 0x39C813}   # table reset loops 0x39C6B4 / 0x39C7AC (step caves)
known |= {0x2A38C6}                                  # 0x2A3870 player count loop (step cave 0x2A38CF)
# 0x39DD4C compares player records A/B by pointer; its loops stay 16/17 because it fills the fixed 17 x 0x180 tables
# in 0x396828's frame (bounds review #32). Reviewed, blocked: no overflow, slots >= 16 not seen until #32 is done.
known |= {0x39E091, 0x39E095, 0x39E09C, 0x39E0A1, 0x39E0A5, 0x39E0AA, 0x39E0AF, 0x39E0B4, 0x39E0B9, 0x39E0BE,
          0x39E10B, 0x39E10F, 0x39E114, 0x39E119}
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/limits/gen_member_known.py. Do not edit. Sorted engine RVAs.\n')
    rows = sorted(known)
    for i in range(0, len(rows), 8):
        f.write(' '.join('0x%06X,' % r for r in rows[i:i + 8]) + '\n')
print(len(known), 'known accesses')
