#!/usr/bin/env python3
"""C12 step 3: encode one cave per imul slot site and emit src/host/SlotPatchTable.inc.
Cave (rel32 targets and the shadow constant are filled in at runtime by SlotPatch.cpp):
    cmp   idx, T            ; T = 16 players / 17 peers (slots that exist in the original object)
    jae   high
    <original imul>         ; slot < T: unchanged address
    jmp   back
  high:
    <original imul>
    add   dst, C            ; C = shadowDelta - T*record  -> same array offset in the shadow object
    jmp   back
"""
import json, sys
REGS = {r: i for i, r in enumerate('rax rcx rdx rbx rsp rbp rsi rdi r8 r9 r10 r11 r12 r13 r14 r15'.split())}
specs = json.load(open(sys.argv[1])); out = sys.argv[2]
def cmp_imm8(reg, v):  n = REGS[reg]; return bytes([0x48 | (n >> 3), 0x83, 0xF8 | (n & 7), v])
def add_imm32(reg):    n = REGS[reg]; return bytes([0x48 | (n >> 3), 0x81, 0xC0 | (n & 7)])  # + imm32
rows = []
for s in specs['auto'] + specs['review']:
    rec = int(s['record'], 16); T = 16 if rec == 0xB0 else 17
    orig = bytes.fromhex(s['bytes'])
    if s['index'] not in REGS or s['dst'] not in REGS: raise SystemExit(f"unexpected register at {s['rva']}")
    c = bytearray()
    c += cmp_imm8(s['index'], T)
    c += b'\x0f\x83'; jae_at = len(c); c += b'\0\0\0\0'
    c += orig
    c += b'\xe9'; back1 = len(c); c += b'\0\0\0\0'
    high = len(c); c[jae_at:jae_at+4] = (high - (jae_at + 4)).to_bytes(4, 'little', signed=True)
    c += orig
    c += add_imm32(s['dst']); cpos = len(c); c += b'\0\0\0\0'
    c += b'\xe9'; back2 = len(c); c += b'\0\0\0\0'
    rows.append((int(s['rva'], 16), orig, bytes(c), cpos, back1, back2, rec, T, s['text']))
with open(out, 'w') as f:
    f.write('// Generated by tools/limits/gen_caves.py from docs/limits-players-sites.json. Do not edit.\n')
    f.write('// rva, original bytes (7), cave bytes, offset of C imm32, offsets of the two jmp-back rel32, record, threshold\n')
    for rva, orig, cave, cpos, b1, b2, rec, T, text in rows:
        f.write(f'{{ 0x{rva:X}, {{ {", ".join(f"0x{x:02X}" for x in orig)} }}, {len(cave)}, '
                f'{{ {", ".join(f"0x{x:02X}" for x in cave)} }}, {cpos}, {b1}, {b2}, 0x{rec:X}, {T} }},  // {text}\n')
print(f'{len(rows)} caves, {sum(len(r[2]) for r in rows)} bytes, max cave {max(len(r[2]) for r in rows)}')
