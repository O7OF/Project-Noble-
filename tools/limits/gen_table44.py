"""C12-L (c): the 17 x 0xC peer table at session+0x446C (block+0x443C; fields +0x446C byte, +0x4470, +0x4474).

Finds every `[base + idx*4 + disp]` operand with disp 0x443C/0x4440/0x4444 (block-relative) or 0x446C/0x4470/0x4474
(session-relative) in the capstone listing of the stock haloreach.dll (stock_text.asm, not in git), encodes it,
checks the encoding length against the next instruction's address, and writes src/host/SlotTableSites.inc.
The index register always holds 3 * peer (checked by hand for all 47; see docs/limits-players-loops.md).
SlotPatch byte-checks every row against the loaded engine before installing anything (all or nothing).

    python -I tools/limits/gen_table44.py build/stock_text.asm src/host/SlotTableSites.inc
"""
import re, sys
R64={'rax':0,'rcx':1,'rdx':2,'rbx':3,'rsp':4,'rbp':5,'rsi':6,'rdi':7}
for i in range(8,16): R64[f'r{i}']=i
R32={'eax':0,'ecx':1,'edx':2,'ebx':3,'esp':4,'ebp':5,'esi':6,'edi':7}
for i in range(8,16): R32[f'r{i}d']=i
R8={'al':0,'cl':1,'dl':2,'bl':3,'spl':4,'bpl':5,'sil':6,'dil':7}
for i in range(8,16): R8[f'r{i}b']=i
NEEDREX8={'spl','bpl','sil','dil'}
lines=open(sys.argv[1]).read().splitlines()
addr_idx={}
pat=re.compile(r'\*4 \+ 0x44(3c|40|44|6c|70|74)\]')
sites=[]
for i,l in enumerate(lines):
    if pat.search(l):
        a,ins=l.split(':\t',1)
        nxt=int(lines[i+1].split(':')[0],16)
        sites.append((int(a,16),ins.strip(),nxt-int(a,16)))
def mem(s):
    m=re.search(r'\[(\w+) \+ (\w+)\*4 \+ (0x[0-9a-f]+)\]',s)
    return R64[m.group(1)],R64[m.group(2)],int(m.group(3),16)
def enc(ins):
    op,rest=ins.split(' ',1)
    B,I,disp=mem(rest)
    parts=[p.strip() for p in re.sub(r'(byte|dword|qword) ptr ','',rest).split(',')]
    W=0; reg=None; opc=None; imm=b''; rex_force=False
    if op=='cmp' and parts[1] in ('-1','0'):
        opc=[0x83] if 'dword' in rest else [0x80]; reg=7; imm=bytes([0xFF if parts[1]=='-1' else 0])
    elif op=='or':
        opc=[0x83]; reg=1; imm=b'\xff'
    elif op=='cmp':
        r=parts[1]
        if r in R32: opc=[0x39]; reg=R32[r]
        else: opc=[0x38]; reg=R8[r]; rex_force=r in NEEDREX8
    elif op=='movsxd':
        W=1; opc=[0x63]; reg=R64[parts[0]]
    elif op=='mov' and parts[0] in R32:
        opc=[0x8B]; reg=R32[parts[0]]
    elif op=='mov':
        r=parts[1]
        if 'qword' in rest: W=1; opc=[0x89]; reg=R64[r]
        elif 'dword' in rest: opc=[0x89]; reg=R32[r]
        else: opc=[0x88]; reg=R8[r]; rex_force=r in NEEDREX8
    rex=0x40|(W<<3)|((reg>>3)<<2)|((I>>3)<<1)|(B>>3)
    out=[]
    if rex!=0x40 or rex_force: out.append(rex)
    out+=opc
    out.append(0x80|((reg&7)<<3)|4)
    out.append((2<<6)|((I&7)<<3)|(B&7))
    out+=list(disp.to_bytes(4,'little'))
    out+=list(imm)
    # destination register overwrites the index register?
    dst = R64.get(parts[0], R32.get(parts[0])) if op in ('movsxd','mov') and not parts[0].startswith('[') and '[' not in parts[0] else None
    return out,B,I,disp,(dst==I)
bad=0
rows=[]
for a,ins,ln in sites:
    b,B,I,disp,ovw=enc(ins)
    ok=len(b)==ln
    if not ok: bad+=1
    rows.append((a-0x180000000,b,B,I,ovw,ins,ok))
    if '-v' in sys.argv: print(f"{a-0x180000000:06X} len {ln} {'OK ' if ok else 'BAD'} {' '.join('%02X'%x for x in b):30} B={B:2} I={I:2} ovw={int(ovw)}  {ins}")
print('sites',len(rows),'bad',bad)
if bad or len(rows) != 47:
    sys.exit('unexpected site list; check the listing')
with open(sys.argv[2], 'w', newline='\n') as f:
    f.write('// Generated by tools/limits/gen_table44.py from the stock listing. Do not edit.\n')
    f.write('// { rva, length, original bytes, base reg, index reg (holds 3 * peer), instruction overwrites index }\n')
    for rva, b, B, I, ovw, ins, ok in rows:
        f.write('{ 0x%06X, %d, { %s }, %d, %d, %s },  // %s\n' % (rva, len(b), ', '.join('0x%02X' % x for x in b), B, I, 'true' if ovw else 'false', ins))
