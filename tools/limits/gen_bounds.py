#!/usr/bin/env python3
"""C12 step 2b: 16/17-slot loop bounds -> src/host/SlotBoundsTable.inc (32-player mode only).

Usage: python -I tools/limits/gen_bounds.py <stock haloreach.dll> docs/limits-players-bounds.json src/host/SlotBoundsTable.inc

Most rows are one `cmp reg, imm8` (opcode 83 /7) whose imm8 is 0x10 (players) or 0x11 (peers). In 32-player mode the
imm8 becomes 0x20 for both: the peer-valid mask is a DWORD, so peers stop at 32, not 33 (slots 17..31 go to the
shadow object, the same split the imul caves use).

Taken from docs/limits-players-bounds.json: every `bit-scan` and every `loop` entry, EXCEPT entries in functions
that also fill a fixed 16/17-entry table outside the session object (bounds review C3 classes, plus the tables
Claude found while reviewing the step loops). Those stay at 16/17 until the tables are grown. The three `other`
entries are not loop bounds and are never changed.
EXTRA adds bounds of the step-cave loops (gen_steps.py) that the trace-based list does not contain.
"""
import json, sys

# Functions left at 16/17 until their tables are handled (see docs/limits-players-loops.md).
BLOCKED = {
    0x00D6B8,   # 16 x 0x20 player list handed to the host interface
    0x38DA74,   # 16 qword pointer array (caller 0x390DB0's frame)
    0x390DB0,   # 16 qword pointer array at rbp+0x150; 16-word name copies (length limit, never raise)
    0x39C6B4,   # 17 x 0xC table at session +0x4440
    0x39DD4C,   # caller-stack 16 x 0x180 table
    0x3C0248,   # 6-byte table at [r15]+0x34
    0x40A760,   # 16 x 0xA0 table at the object base (vtable 0xA47750)
    0x41E7C8,   # 6-byte table at [rsi+8]+0x34; 41E884's 17 x 6 stack table
    0x41F510,   # 16 x 0xA0 table in the 0x4E0E910 singleton, 17 x 6 stack table
}

# (rva, original imm8) for loops reached only through the step caves
EXTRA = [
    (0x41198D, 0x10),   # 4118C8: cmp r9d,0x10
    (0x44BDEA, 0x10),   # 44BCE8: cmp r10d,0x10 (step cave 0x44BDE3)
    (0x44CCF6, 0x10),   # 44C9BC: cmp ecx,0x10 (step cave 0x44CCEF)
]

# Other encodings in the step-cave loops: (rva, stock bytes, 32-player bytes, what)
RAW = [
    (0x391B4A, 'BEFFFF0100', 'BEFFFFFFFF', '3919E4: mov esi,0x1ffff (17-peer mask) -> all 32 bits'),
    (0x408EE0, 'B910000000', 'B920000000', '408DDC: mov ecx,0x10 (player loop bound)'),
    (0x408F22, '8D480F',     '8D481F',     '408DDC: lea ecx,[rax+0xf] (bound re-load, 0x10 -> 0x20)'),
]

def main():
    dll = open(sys.argv[1], 'rb').read()
    entries = json.load(open(sys.argv[2]))
    out = sys.argv[3]
    rows, skipped = [], []
    seen = set()
    cand = [(int(e['rva'], 16), int(e['function'], 16), e['kind'], e['insn']) for e in entries]
    cand += [(rva, None, 'extra', f'imm 0x{imm:x}') for rva, imm in EXTRA]
    for rva, fn, kind, insn in cand:
        if rva in seen: continue
        seen.add(rva)
        if kind == 'other' or (fn is not None and fn in BLOCKED):
            skipped.append((rva, kind, insn)); continue
        at = rva - 0x1000 + 0x400
        b = dll[at:at + 4]
        # [REX] 83 /7 imm8, ModRM register form (mod = 11)
        i = 1 if 0x40 <= b[0] <= 0x4F else 0
        if b[i] != 0x83 or (b[i + 1] & 0xF8) != 0xF8 or b[i + 2] not in (0x10, 0x11):
            raise SystemExit(f'0x{rva:X}: not cmp reg,imm8 0x10/0x11: {b.hex()} ({insn})')
        old = bytes(b[:i + 3]); new = bytearray(old); new[i + 2] = 0x20
        rows.append((rva, old, bytes(new), f'{kind}: {insn}'))
    for rva, old, new, what in RAW:
        old, new = bytes.fromhex(old), bytes.fromhex(new)
        at = rva - 0x1000 + 0x400
        if dll[at:at + len(old)] != old: raise SystemExit(f'0x{rva:X}: expected {old.hex()}')
        rows.append((rva, old, new, what))
    rows.sort()
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by tools/limits/gen_bounds.py. Do not edit.\n')
        f.write('// rva, length, stock bytes (checked), 32-player bytes\n')
        hx = lambda b: ", ".join(f"0x{x:02X}" for x in list(b) + [0] * (8 - len(b)))
        for rva, old, new, what in rows:
            f.write(f'{{ 0x{rva:X}, {len(old)}, {{ {hx(old)} }}, {{ {hx(new)} }} }},  // {what}\n')
    print(f'{len(rows)} bounds, {len(skipped)} left at 16/17')
    for s in skipped: print(f'  kept 0x{s[0]:X} {s[1]} {s[2]}')

if __name__ == '__main__':
    main()
